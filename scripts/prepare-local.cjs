// file:// cannot fetch HTML. Generate only the markup needed by same-origin srcdoc frames.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const pages = {
  profileForm: read('features/employee-profile/forms/index.html'),
  tickets: {
    employee: read('features/tickets/shared/employee/index.html'),
    manager: read('features/tickets/shared/manager/index.html')
  }
};
const output = '// Generated by node scripts/prepare-local.cjs. Edit the source HTML, not this file.\n' +
  'window.essEmbeddedPages=' + JSON.stringify(pages).replace(/</g, '\\u003c') + ';\n';
fs.writeFileSync(path.join(root, 'data/embedded-pages.js'), output);
console.log('Prepared Profile and Ticket iframe markup from source HTML.');
